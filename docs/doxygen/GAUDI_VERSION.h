#pragma once

// This file is only used to document GAUDI_VERSION.h, which is generated by CMake
// (gaudi_generate_version_header_file(), called in the top level CMakeLists.txt)
// when Gaudi is configured, and installed with the other headers. It is never
// compiled: the values are those of the version of Gaudi being built.

/** @file GAUDI_VERSION.h
 *
 * Version of Gaudi, to be used as
 *
 * @code{.cpp}
 * #include <GAUDI_VERSION.h>
 *
 * #if GAUDI_VERSION >= CALC_GAUDI_VERSION( 40, 2 )
 *   // code needing Gaudi v40r2 or newer
 * #endif
 * @endcode
 *
 * The file is generated from the version of the project in the top level
 * `CMakeLists.txt`, for example Gaudi v41r0 has `GAUDI_MAJOR_VERSION` 41,
 * `GAUDI_MINOR_VERSION` 0 and `GAUDI_PATCH_VERSION` 0 (the patch version is
 * 0 if the project version has no patch number).
 */

/// Build a number representing a version, to compare versions (the patch number
/// is not taken into account).
/// @param maj major version
/// @param min minor version
#define CALC_GAUDI_VERSION( maj, min ) ( ( ( maj ) << 16 ) + ( min ) )

/// Major version of Gaudi (the 41 of v41r0).
#define GAUDI_MAJOR_VERSION

/// Minor version of Gaudi (the 0 of v41r0).
#define GAUDI_MINOR_VERSION

/// Patch version of Gaudi (the 0 of v41r0p0), 0 if the version has no patch number.
#define GAUDI_PATCH_VERSION

/// Version of Gaudi as a number that can be compared with the result of
/// CALC_GAUDI_VERSION (without the patch version).
#define GAUDI_VERSION CALC_GAUDI_VERSION( GAUDI_MAJOR_VERSION, GAUDI_MINOR_VERSION )
